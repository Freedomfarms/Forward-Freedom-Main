import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";
import { build } from "vite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "extension", "dist");

if (path.relative(path.join(root, "extension"), outDir) !== "dist") {
  throw new Error("Refusing to write the content script outside extension/dist.");
}

await build({
  configFile: false,
  root,
  publicDir: false,
  logLevel: "warn",
  build: {
    target: "chrome114",
    outDir,
    emptyOutDir: true,
    copyPublicDir: false,
    sourcemap: false,
    minify: false,
    cssCodeSplit: false,
    reportCompressedSize: false,
    lib: {
      entry: path.join(root, "extension", "content.js"),
      formats: ["iife"],
      name: "FreedomCaptureContent",
      fileName: () => "content.js",
    },
    rollupOptions: {
      output: {
        banner: "/* Generated by scripts/build-extension.mjs. */",
      },
    },
  },
});

const names = readdirSync(outDir);
if (names.length !== 1 || names[0] !== "content.js") {
  throw new Error(
    `Expected only extension/dist/content.js, found ${names.join(", ") || "nothing"}.`
  );
}

const file = path.join(outDir, "content.js");
const formatted = await prettier.format(readFileSync(file, "utf8"), { filepath: file });
writeFileSync(file, formatted);
